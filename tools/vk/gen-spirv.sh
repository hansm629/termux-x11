#!/bin/sh
# Compiles app/src/main/cpp/lorie/shaders/quad.{vert,frag} to SPIR-V (Vulkan 1.1), validates it, and writes
# the words as C arrays to app/src/main/cpp/lorie/vk_shaders.h - which is committed, so building the app
# needs no shader compiler. tests/host/run.sh regenerates it and fails if the committed one differs.
#
# usage: gen-spirv.sh [OUTPUT]     (default: the committed header)
# Needs glslc and spirv-val (Termux: pkg install shaderc spirv-tools).
set -e
HERE=$(cd "$(dirname "$0")" && pwd)
LORIE=$(cd "$HERE/../../app/src/main/cpp/lorie" && pwd)
OUT=${1:-$LORIE/vk_shaders.h}
TMP=$(mktemp -d "${TMPDIR:-/tmp}/spirv.XXXXXX")
trap 'rm -rf "$TMP"' EXIT
for s in vert frag; do
    glslc --target-env=vulkan1.1 -O -o "$TMP/quad.$s.spv" "$LORIE/shaders/quad.$s"
    spirv-val --target-env vulkan1.1 "$TMP/quad.$s.spv"
done
{
    echo "// Generated by tools/vk/gen-spirv.sh from shaders/quad.vert and shaders/quad.frag - do not edit."
    echo "#pragma once"
    echo "#include <stdint.h>"
    for s in vert frag; do
        echo "static const uint32_t lorieVkQuad_$s[] = {"
        od -An -v -tx4 -w16 "$TMP/quad.$s.spv" | sed -e 's/^ *//' -e 's/ *$//' -e 's/\([0-9a-f]\{8\}\)/0x\1,/g' -e 's/^/    /'
        echo "};"
    done
} > "$OUT"
